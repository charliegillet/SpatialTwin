"""Generate the building-v2 frontend fixtures and the outcome matrix from the real local planner.

    .venv/bin/python tools/gen_twin_fixtures.py

Writes frontend/src/twin/fixtures/building-v2.json (byte copy of venue/building_v2.json),
frontend/src/twin/fixtures/door-plan-<case>.json (real planner outputs, hazards at zone centroids) and
docs/demo/building-v2-matrix.md. No provider, serial or network access.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app.hazard.door_planner import plan_doors  # noqa: E402
from backend.app.venues.model import VENUE_FILE, load_building_v2  # noqa: E402
from backend.app.venues.schemas import DoorPlanRequest  # noqa: E402

FIXTURES = ROOT / "frontend" / "src" / "twin" / "fixtures"
MATRIX = ROOT / "docs" / "demo" / "building-v2-matrix.md"
HAZARD_TYPES = ["FIRE", "SMOKE", "GAS", "CHEMICAL", "WATER"]

CASES = {
    "none": [],
    "fire-lobby": [("FIRE", "LOBBY")],
    "fire-hall": [("FIRE", "HALL")],
    "smoke-hall": [("SMOKE", "HALL")],
    "gas-hall": [("GAS", "HALL")],
    "gas-kitchen": [("GAS", "KITCHEN")],
    "chemical-east-corr": [("CHEMICAL", "EAST_CORR")],
    "water-west-corr": [("WATER", "WEST_CORR")],
}


def centroid(venue, zone_id):
    poly = venue.zone(zone_id).polygon
    xs = [p[0] for p in poly]
    ys = [p[1] for p in poly]
    return (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2  # zones are axis-aligned rectangles


def request_for(venue, hazards):
    items = []
    for i, (kind, zone_id) in enumerate(hazards):
        x, y = centroid(venue, zone_id)
        items.append({"id": f"h{i + 1}", "type": kind, "position": {"x": x, "y": y}, "source": "simulated"})
    return DoorPlanRequest(hazards=items)


def summarize(response):
    opened = [d.id for d in response.doors if d.decided_by == "door_planner"]
    released = [d.id for d in response.doors if d.decided_by == "hazard_rule" and d.state == "closed" and d.changed]
    locked = [d.id for d in response.doors if d.locked]
    unsafe = [e.id for e in response.exits if not e.safe]
    return opened, released, locked, unsafe


def main() -> None:
    venue = load_building_v2()
    FIXTURES.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(VENUE_FILE, FIXTURES / "building-v2.json")
    for name, hazards in CASES.items():
        response = plan_doors(venue, request_for(venue, hazards))
        (FIXTURES / f"door-plan-{name}.json").write_text(
            json.dumps(response.model_dump(mode="json"), indent=2) + "\n")
        print(f"fixture {name}: {response.chosen.completed_crossings}/{response.chosen.initial_population}")

    rows = []
    for zone in venue.zones:
        for kind in HAZARD_TYPES:
            r = plan_doors(venue, request_for(venue, [(kind, zone.id)]))
            opened, released, locked, unsafe = summarize(r)
            rows.append((zone.id, kind, r, opened, released, locked, unsafe))
    no_hazard = rows[0][2].no_hazard_completed
    lines = [
        "<!-- GENERATED by tools/gen_twin_fixtures.py from the real local door planner. Do not edit by hand. -->",
        "# building-v2 outcome matrix",
        "",
        "Generated. One hazard at the centroid of each zone, default untenable times, "
        f"{venue.default_horizon_seconds} s horizon, {venue.time_step_seconds} s step, "
        f"{rows[0][2].chosen.initial_population} synthetic people. Counts are modeled crossings inside the declared "
        "building-v2 model, never survival or casualty predictions.",
        "",
        f"No-hazard reference: {no_hazard} modeled crossings.",
        "",
        "| Zone | Hazard | Chosen | Baseline | Gain | Opened by planner | Released (closed to entry) | Locked | Unsafe exits | Exposure (people-s) |",
        "| --- | --- | ---: | ---: | ---: | --- | --- | --- | --- | ---: |",
    ]
    for zone_id, kind, r, opened, released, locked, unsafe in rows:
        gain = r.chosen.completed_crossings - r.baseline.completed_crossings
        lines.append(
            f"| {zone_id} | {kind} | {r.chosen.completed_crossings} | {r.baseline.completed_crossings} | {gain:+d} | "
            f"{', '.join(opened) or '-'} | {', '.join(released) or '-'} | {', '.join(locked) or '-'} | "
            f"{', '.join(unsafe) or '-'} | {r.chosen.modeled_exposure_people_seconds} |")
    lines += ["", "Chosen = best checker-valid door state found by the local planner; Baseline = same hazard with every "
              "planner-controllable door at its default state."]
    MATRIX.write_text("\n".join(lines) + "\n")
    print(f"wrote {MATRIX.relative_to(ROOT)} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
