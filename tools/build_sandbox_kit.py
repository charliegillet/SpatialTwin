"""Generate the agent sandbox kit: standalone copies of the solver, checker, effects and scenario grammar + manifest.

Run from the repository root:  .venv/bin/python -m tools.build_sandbox_kit          (writes the kit)
                               .venv/bin/python -m tools.build_sandbox_kit --check  (exit 1 when the kit is stale)

Hand-written kit files (``agents/**``, ``kit/spatialtwin_kit/{model,estimate,sweep}.py``) live in the kit directory
itself; this tool only rewrites the backend imports of the copied modules and writes ``manifest.json`` with a
sha256 per file, its sandbox target and the inline-source limits from agent-environment.md (1 MB per file, 2 MB in
total, read 23 Oct 2026). No network, no provider call.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Dict, Tuple

REPO_ROOT = Path(__file__).resolve().parents[1]
KIT_DIR = REPO_ROOT / "backend" / "app" / "ai" / "managed" / "sandbox_kit"
PACKAGE = "kit/spatialtwin_kit"
INLINE_FILE_LIMIT = 1_000_000
INLINE_TOTAL_LIMIT = 2_000_000
COPIES = {  # kit path -> repo source
    f"{PACKAGE}/checker_v2.py": "backend/app/planner/checker_v2.py",
    f"{PACKAGE}/flow_solver_v2.py": "backend/app/planner/flow_solver_v2.py",
    f"{PACKAGE}/effects_v2.py": "backend/app/hazard/effects_v2.py",
    f"{PACKAGE}/scenarios.py": "backend/app/ai/managed/scenarios.py",
}
INIT = ('"""SpatialTwin solver kit for the agent sandbox (generated package; see manifest.json)."""\n')
HEADER = ("# GENERATED by tools/build_sandbox_kit.py from {source} (sha256 {digest}). Do not edit: regenerate.\n"
          "# Standalone copy for the agent sandbox; the laptop's local checker remains the authority.\n")
NETWORKX = ("try:  # the sandbox image has no networkx; solve() needs it, estimate.py does not\n"
            "    import networkx as nx\n"
            "except ImportError:  # pragma: no cover\n"
            "    nx = None\n")
REWRITES = (
    (re.compile(r"^from backend\.app\.planner\.(\w+) import", re.M), r"from .\1 import"),
    (re.compile(r"^from backend\.app\.hazard\.(\w+) import", re.M), r"from .\1 import"),
    (re.compile(r"^from backend\.app\.venues\.model import", re.M), "from .model import"),
)


class KitError(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rewrite(source_path: str, text: str) -> str:
    out = text
    for pattern, replacement in REWRITES:
        out = pattern.sub(replacement, out)
    out = out.replace("import networkx as nx\n", NETWORKX, 1)
    if "backend." in out:
        raise KitError(f"unrewritten backend import left in {source_path}")
    return HEADER.format(source=source_path, digest=sha256(text.encode())[:16]) + out


def target_for(kit_path: str) -> str:
    """Sandbox target (relative to /, as the inline-source examples use)."""
    if kit_path.startswith("agents/"):
        return ".agents/" + kit_path[len("agents/"):]
    if kit_path.startswith("kit/"):
        return "workspace/kit/" + kit_path[len("kit/"):]
    raise KitError(f"no sandbox target for {kit_path}")


def generated_files(repo_root: Path = REPO_ROOT) -> Dict[str, Tuple[bytes, str]]:
    """kit path -> (content, source path) for every generated file."""
    files: Dict[str, Tuple[bytes, str]] = {f"{PACKAGE}/__init__.py": (INIT.encode(), "")}
    for kit_path, source in COPIES.items():
        text = (repo_root / source).read_text()
        if kit_path.endswith("scenarios.py"):  # stdlib only: copied verbatim so both sides parse identically
            content = HEADER.format(source=source, digest=sha256(text.encode())[:16]) + text
        else:
            content = rewrite(source, text)
        files[kit_path] = (content.encode(), source)
    return files


def hand_written(kit_dir: Path = KIT_DIR) -> Dict[str, bytes]:
    out = {}
    for path in sorted(kit_dir.rglob("*")):
        if not path.is_file() or "__pycache__" in path.parts or path.name == "manifest.json":
            continue
        rel = path.relative_to(kit_dir).as_posix()
        out[rel] = path.read_bytes()
    return out


def build(kit_dir: Path = KIT_DIR, repo_root: Path = REPO_ROOT) -> Dict[str, object]:
    """Everything the kit should contain: {"files": {kit path: bytes}, "manifest": dict}. Writes nothing."""
    generated = generated_files(repo_root)
    files = {rel: data for rel, data in hand_written(kit_dir).items() if rel not in generated}
    files.update({rel: data for rel, (data, _) in generated.items()})
    entries = []
    for rel in sorted(files):
        data = files[rel]
        if len(data) > INLINE_FILE_LIMIT:
            raise KitError(f"{rel} is {len(data)} bytes; the inline-source limit is {INLINE_FILE_LIMIT}")
        entry = {"path": rel, "target": target_for(rel), "sha256": sha256(data), "bytes": len(data)}
        if rel in generated and generated[rel][1]:
            entry["source"] = generated[rel][1]
            entry["source_sha256"] = sha256((repo_root / generated[rel][1]).read_bytes())
        entries.append(entry)
    total = sum(e["bytes"] for e in entries)
    if total > INLINE_TOTAL_LIMIT:
        raise KitError(f"kit is {total} bytes; the inline-source total limit is {INLINE_TOTAL_LIMIT}")
    manifest = {
        "kit_version": sha256("".join(e["sha256"] for e in entries).encode())[:16],
        "files": entries, "total_bytes": total,
        "limits": {"inline_file_bytes": INLINE_FILE_LIMIT, "inline_total_bytes": INLINE_TOTAL_LIMIT,
                   "source": "CLAUDE_BUILD_HANDOFF/reference/google/agent-environment.md (read 23 Oct 2026)"},
        "note": "Generated by tools/build_sandbox_kit.py. Copies run standalone in the sandbox; the laptop's "
                "local checker re-runs every claim and decides.",
    }
    return {"files": files, "manifest": manifest}


def manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, indent=1, sort_keys=True) + "\n").encode()


def stale_paths(kit_dir: Path = KIT_DIR, repo_root: Path = REPO_ROOT) -> list:
    built = build(kit_dir, repo_root)
    stale = [rel for rel, data in built["files"].items()
             if not (kit_dir / rel).is_file() or (kit_dir / rel).read_bytes() != data]
    manifest = kit_dir / "manifest.json"
    if not manifest.is_file() or manifest.read_bytes() != manifest_bytes(built["manifest"]):
        stale.append("manifest.json")
    return stale


def write(kit_dir: Path = KIT_DIR, repo_root: Path = REPO_ROOT) -> dict:
    built = build(kit_dir, repo_root)
    for rel, data in built["files"].items():
        path = kit_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
    (kit_dir / "manifest.json").write_bytes(manifest_bytes(built["manifest"]))
    return built["manifest"]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed kit is stale")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_paths()
        print("sandbox kit is current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    manifest = write()
    print(f"wrote {len(manifest['files'])} files, {manifest['total_bytes']} bytes, kit {manifest['kit_version']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
