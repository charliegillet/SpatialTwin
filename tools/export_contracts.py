"""Export Pydantic schemas and TypeScript declarations from the same source."""
import json
from pathlib import Path
from backend.app.roomlab import contracts

ROOT=Path(__file__).resolve().parents[1]
def ts(s):
    if '$ref' in s:return s['$ref'].split('/')[-1]
    if 'anyOf' in s:return ' | '.join(ts(x) for x in s['anyOf'])
    if 'const' in s:return json.dumps(s['const'])
    if 'enum' in s:return ' | '.join(json.dumps(x) for x in s['enum'])
    t=s.get('type')
    if t=='array':return f'Array<{ts(s.get("items",{}))}>'
    if t=='object':return '{ '+ '; '.join(f'{k}{"" if k in s.get("required",[]) else "?"}: {ts(v)}' for k,v in s.get('properties',{}).items())+' }'
    return {'string':'string','number':'number','integer':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
def main():
    definitions={}
    for name,value in vars(contracts).items():
        if isinstance(value,type) and issubclass(value,contracts.Contract) and value is not contracts.Contract:
            schema=value.model_json_schema();definitions.update(schema.pop('$defs',{}));definitions[name]=schema
    (ROOT/'contracts').mkdir(exist_ok=True)
    (ROOT/'contracts/roomscene-v1.schema.json').write_text(json.dumps(definitions,indent=2)+'\n')
    output='// Generated by python -m tools.export_contracts. Do not edit.\n'
    output+='\n'.join(f'export type {name} = {ts(schema)};' for name,schema in sorted(definitions.items()))+'\n'
    (ROOT/'frontend/src/roomlab/contracts.generated.ts').write_text(output)
if __name__=='__main__':main()
